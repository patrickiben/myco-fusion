"""Load spectra bundled with the package."""
from __future__ import annotations

import csv
import json
from functools import lru_cache
from pathlib import Path

import numpy as np

DATA = Path(__file__).resolve().parent / "data"
NATURAL_OBJECTS = "natural_objects_27band.csv"
FINDINGS = "findings.json"


@lru_cache(maxsize=1)
def natural_objects():
    """Measured reflectance of 532 samples of natural objects on the 27-band grid.

    Derived from Gutiérrez et al. 2025 (CC BY 4.0): repeats averaged per sample,
    interpolated to 420-680 nm and clipped to [0, 1]. See docs/DATA.md.
    """
    with (DATA / NATURAL_OBJECTS).open(encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle))
    bands = [name for name in rows[0] if name.isdigit()]
    return {
        "ids": [row["sample_id"] for row in rows],
        "domain": [row["domain"] for row in rows],
        "object": [row["object"] for row in rows],
        "color": [row["color"] for row in rows],
        "group": [row["group"] for row in rows],
        "spectra": np.array([[float(row[band]) for band in bands] for row in rows]),
    }


def findings():
    """Study summary generated by study/build_report.py."""
    return json.loads((DATA / FINDINGS).read_text(encoding="utf-8"))
